// Package runtime is checked in with logosRuntimeHooks = true
// (src/runtime/logos_features.go), so bootstrap, `go tool compile`, and
// gccgo keep today's behavior. For a build whose complete action graph
// cannot reach any loGo/s feature, Builder.Do selects the disabled variant
// instead: b.build swaps a generated objdir constant file into the local
// compile of package runtime only. The selection is one boolean, derived at
// Do entry before any action ID is computed, immutable for that execution.
// It is hashed into runtime's action ID only; consumers track a change
// through runtime's ordinary dependency content ID. Nothing exposes the
// selection as a flag, env, or config.
const (
	logosRuntimePkg  = "runtime"
	logosPluginPkg   = "plugin"
	logosFeaturesSrc = "logos_features.go"  // checked-in default, Dir-relative
	logosFeaturesGen = "_logos_features.go" // generated disabled variant, objdir-relative
)

const logosFeaturesGenBody = `// Code generated by cmd/go; DO NOT EDIT.
// Runtime hook variant selected for this build action graph.

package runtime

const logosRuntimeHooks = false
`

// logosRuntimeHooksFor reports whether the action graph rooted at root must
// compile runtime with hooks enabled. Called once at Do entry: all loading,
// including test variants, has completed, and no action ID has been
// computed.
//
// Hooks stay enabled whenever the graph might reach them: any package is or
// imports logos/rt (every loGo/s package unconditionally imports it, and Go
// importers of loGo/s packages gain the same implicit import, so this
// closure check subsumes all lowering paths including generated test
// mains); any package is or imports package plugin (a host that can call
// plugin.Open must run the runtime a -buildmode=plugin .so was built with,
// or plugin's pkghash check rejects the load); any package is a runtime
// test variant (runtime's private hook tests exercise the guarded helpers
// directly); or the invocation builds shared, plugin, c-shared, or
// c-archive artifacts, or uses -linkshared, so both sides of any
// shared/plugin pairing see the enabled runtime. cfg.Logos is deliberately
// not consulted: logos/rt is ordinary Go and plain Go programs may import
// it explicitly.
func logosRuntimeHooksFor(root *Action) bool {
	if cfg.BuildLinkshared {
		return true
	}
	switch cfg.BuildBuildmode {
	case "plugin", "shared", "c-shared", "c-archive":
		return true
	}
	seen := make(map[*Action]bool)
	var walk func(*Action) bool
	walk = func(a *Action) bool {
		if a == nil || seen[a] {
			return false
		}
		seen[a] = true
		if p := a.Package; p != nil && logosHooksForcedForPkg(p) {
			return true
		}
		for _, a1 := range a.Deps {
			if walk(a1) {
				return true
			}
		}
		return false
	}
	return walk(root)
}

func logosHooksForcedForPkg(p *load.Package) bool {
	if p.ForTest == logosRuntimePkg {
		return true
	}
	if p.ImportPath == load.LogosRTPkg || p.ImportPath == logosPluginPkg {
		return true
	}
	for _, imports := range [][]string{p.Imports, p.Internal.CompiledImports} {
		for _, imp := range imports {
			if imp == load.LogosRTPkg || imp == logosPluginPkg {
				return true
			}
		}
	}
	return false
}

// logosFeaturesSource reports whether name is the checked-in hooks constant
// file in a local compile list, in any rewritten form: plain
// ("logos_features.go", Dir-relative), coverage-instrumented
// ("logos_features.cover.go", objdir-absolute), or cgo-processed
// ("logos_features.cgo1.go").
func logosFeaturesSource(name string) bool {
	n := filepath.Base(name)
	n = strings.TrimSuffix(n, ".go")
	n = strings.TrimSuffix(n, ".cover")
	n = strings.TrimSuffix(n, ".")
	n = strings.TrimSuffix(n, ".cgo1")
	return n == strings.TrimSuffix(logosFeaturesSrc, ".go")
}

// logosFeaturesOff swaps the generated disabled constant file into the
// local compile list for a runtime build, leaving p.GoFiles untouched so
// the checked-in default stays hashed by buildActionID and listed by go
// list and vet. The swap is strict: the checked-in file must be among the
// local inputs, so a compile never sees two definitions of the constant and
// a disabled selection never silently compiles with hooks on.
func (b *Builder) logosFeaturesOff(a *Action, gofiles []string) ([]string, error) {
	p := a.Package
	out := make([]string, 0, len(gofiles)+1)
	found := false
	for _, f := range gofiles {
		if logosFeaturesSource(f) {
			found = true
			continue
		}
		out = append(out, f)
	}
	if !found {
		return nil, fmt.Errorf("runtime hook variant disabled but %s not among compile inputs of %s", logosFeaturesSrc, p.ImportPath)
	}
	if err := b.Shell(a).writeFile(a.Objdir+logosFeaturesGen, []byte(logosFeaturesGenBody)); err != nil {
		return nil, err
	}
	return append(out, a.Objdir+logosFeaturesGen), nil
}
