// Package drbg provides cryptographically secure random bytes
// usable by FIPS code. In FIPS mode it uses an SP 800-90A Rev. 1
// Deterministic Random Bit Generator (DRBG). Otherwise,
// it uses the operating system's random number generator.
package drbg

import (
	"crypto/internal/fips140"
	"crypto/internal/sysrand"
	"io"
	"math/rand/v2"
	"slices"
	"sync"
	"sync/atomic"
	"unsafe"
)

// The DRBGs form an SP 800-90C RBGC tree (Section 7): the root is seeded from
// the entropy source at init() time, and is only used to seed the DRBG
// instances in the [slots], which produce the output of [Read].
//
// This makes the 32 MiB allocation of scratch memory for the entropy source
// happen once, predictably, and before the working set is loaded.
var root struct {
	sync.Mutex
	drbg *Counter
}

func init() {
	if fips140.Enabled {
		root.Lock()
		defer root.Unlock()
		seed := getEntropy()
		root.drbg = NewCounter(seed)
		clear(seed[:])
	}
}

// rootSeed returns seed material generated by the root DRBG to instantiate or
// reseed the DRBG instance in a [slot], per SP 800-90C, Sections 7.2.1.2 and
// 7.2.3.2.1. Each seed must be used only once and then destroyed.
func rootSeed() *[SeedSize]byte {
	root.Lock()
	defer root.Unlock()
	if root.drbg == nil {
		// FIPS 140-3 mode was enabled after init time, which only tests do.
		seed := getEntropy()
		root.drbg = NewCounter(seed)
		clear(seed[:])
	}
	seed := new([SeedSize]byte)
	if reseedRequired := root.drbg.Generate(seed[:], nil); reseedRequired {
		// The root only generates a seed when a slot is instantiated or
		// reseeded, so it can't reach its reseed interval of 2⁴⁸ requests.
		panic("fips140/drbg: internal error: root DRBG reseed required")
	}
	return seed
}

// The slots are a set of persistent DRBG instances seeded from the root. A new
// slot is added only when all the existing ones are in use.
var slots struct {
	all  atomic.Pointer[[]*slot]
	grow sync.Mutex // held while replacing all
}

type slot struct {
	sync.Mutex
	drbg *Counter // nil until seeded

	// Prevent false sharing between slots allocated next to each other.
	_ [128 - unsafe.Sizeof(sync.Mutex{}) - unsafe.Sizeof((*Counter)(nil))]byte
}

// acquireSlot returns a locked slot.
// The slot's drbg is nil if it is not seeded yet.
// The caller must call [slot.Unlock] once done.
func acquireSlot() *slot {
	for {
		var all []*slot
		if p := slots.all.Load(); p != nil {
			all = *p
		}

		n := len(all)
		if n > 0 {
			// Try all slots, starting from a random one.
			start := rand.IntN(n)
			for i := range n {
				if s := all[(start+i)%n]; s.TryLock() {
					return s
				}
			}
		}

		// All slots are in use, add a new one.
		slots.grow.Lock()
		if p := slots.all.Load(); p != nil && len(*p) != n {
			// Another goroutine added a slot in the meantime.
			slots.grow.Unlock()
			continue
		}
		s := new(slot)
		s.Lock()
		// Clip all to force append to make a copy, so that next never shares
		// a backing array with a slice other goroutines might be reading.
		next := append(slices.Clip(all), s)
		slots.all.Store(&next)
		slots.grow.Unlock()
		return s
	}
}

// Read fills b with cryptographically secure random bytes. In FIPS mode, it
// uses an SP 800-90A Rev. 1 Deterministic Random Bit Generator (DRBG).
// Otherwise, it uses the operating system's random number generator.
func Read(b []byte) {
	if testingReader != nil {
		fips140.RecordNonApproved()
		// Avoid letting b escape in the non-testing case.
		bb := make([]byte, len(b))
		testingReader.Read(bb)
		copy(b, bb)
		return
	}

	if !fips140.Enabled {
		sysrand.Read(b)
		return
	}

	// At every read, 128 random bits from the operating system are mixed as
	// additional input, to make the output as strong as non-FIPS randomness.
	// This is not credited as entropy for FIPS purposes, as allowed by Section
	// 8.7.2: "Note that a DRBG does not rely on additional input to provide
	// entropy, even though entropy could be provided in the additional input".
	additionalInput := new([SeedSize]byte)
	sysrand.Read(additionalInput[:16])

	s := acquireSlot()
	defer s.Unlock()
	if s.drbg == nil {
		seed := rootSeed()
		s.drbg = NewCounter(seed)
		clear(seed[:])
	}

	for len(b) > 0 {
		size := min(len(b), maxRequestSize)
		if reseedRequired := s.drbg.Generate(b[:size], additionalInput); reseedRequired {
			// See SP 800-90A Rev. 1, Section 9.3.1, Steps 6-8, as explained in
			// Section 9.3.2: if Generate reports a reseed is required, the
			// additional input is passed to Reseed along with the entropy and
			// then nulled before the next Generate call.
			seed := rootSeed()
			s.drbg.Reseed(seed, additionalInput)
			clear(seed[:])
			clear(additionalInput[:])
			additionalInput = nil
			continue
		}
		b = b[size:]
	}
	if additionalInput != nil {
		clear(additionalInput[:])
	}
}

var testingReader io.Reader

// SetTestingReader sets a global, deterministic cryptographic randomness source
// for testing purposes. Its Read method must never return an error, it must
// never return short, and it must be safe for concurrent use.
//
// This is only intended to be used by the testing/cryptotest package.
func SetTestingReader(r io.Reader) {
	testingReader = r
}

// DefaultReader is a sentinel type, embedded in the default
// [crypto/rand.Reader], used to recognize it when passed to
// APIs that accept a rand io.Reader.
//
// Any [io.Reader] that embeds this type is assumed to
// call [Read] as its [io.Reader.Read] method.
type DefaultReader struct{}

func (d DefaultReader) defaultReader() {}

// IsDefaultReader reports whether the r embeds the [DefaultReader] type.
func IsDefaultReader(r io.Reader) bool {
	_, ok := r.(interface{ defaultReader() })
	return ok
}

// ReadWithReader uses Reader to fill b with cryptographically secure random
// bytes. It is intended for use in APIs that expose a rand io.Reader.
func ReadWithReader(r io.Reader, b []byte) error {
	if IsDefaultReader(r) {
		Read(b)
		return nil
	}

	fips140.RecordNonApproved()
	_, err := io.ReadFull(r, b)
	return err
}
