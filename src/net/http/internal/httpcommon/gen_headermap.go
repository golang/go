// gen_headermap writes zheadermap.go, the switches that map common header
// names between their canonical and lowercase forms. Run it with go generate.

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"net/textproto"
	"os"
)

// commonHeaders lists the lowercase forms of common header names.
var commonHeaders = []string{
	"accept",
	"accept-charset",
	"accept-encoding",
	"accept-language",
	"accept-ranges",
	"age",
	"access-control-allow-credentials",
	"access-control-allow-headers",
	"access-control-allow-methods",
	"access-control-allow-origin",
	"access-control-expose-headers",
	"access-control-max-age",
	"access-control-request-headers",
	"access-control-request-method",
	"allow",
	"authorization",
	"cache-control",
	"content-disposition",
	"content-encoding",
	"content-language",
	"content-length",
	"content-location",
	"content-range",
	"content-type",
	"cookie",
	"date",
	"etag",
	"expect",
	"expires",
	"from",
	"host",
	"if-match",
	"if-modified-since",
	"if-none-match",
	"if-unmodified-since",
	"last-modified",
	"link",
	"location",
	"max-forwards",
	"origin",
	"proxy-authenticate",
	"proxy-authorization",
	"range",
	"referer",
	"refresh",
	"retry-after",
	"server",
	"set-cookie",
	"strict-transport-security",
	"trailer",
	"transfer-encoding",
	"user-agent",
	"vary",
	"via",
	"www-authenticate",
	"x-forwarded-for",
	"x-forwarded-proto",
}

func main() {
	var b bytes.Buffer
	b.WriteString(`// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by go run gen_headermap.go; DO NOT EDIT.

package httpcommon

// lowerCommonHeader returns the lowercase form of v
// if v is a common header name in canonical form, and "" otherwise.
func lowerCommonHeader(v string) string {
	switch v {
`)
	for _, v := range commonHeaders {
		fmt.Fprintf(&b, "case %q:\nreturn %q\n", textproto.CanonicalMIMEHeaderKey(v), v)
	}
	b.WriteString(`}
	return ""
}

// canonCommonHeader returns the canonical form of v
// if v is a common header name in lowercase, and "" otherwise.
func canonCommonHeader(v string) string {
	switch v {
`)
	for _, v := range commonHeaders {
		fmt.Fprintf(&b, "case %q:\nreturn %q\n", v, textproto.CanonicalMIMEHeaderKey(v))
	}
	b.WriteString(`}
	return ""
}
`)

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zheadermap.go", out, 0o666); err != nil {
		log.Fatal(err)
	}
}
