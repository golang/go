#include "textflag.h"

// func crc64FoldPMULL(crc uint64, p []byte, k *[10]uint64, res *[16]byte)
TEXT ·crc64FoldPMULL(SB),NOSPLIT,$0-48
	MOVD	crc+0(FP), R9
	MOVD	p_base+8(FP), R13
	MOVD	p_len+16(FP), R11
	MOVD	k+32(FP), R5
	MOVD	res+40(FP), R6

	VLD1.P	64(R5), [V8.B16, V9.B16, V10.B16, V11.B16]
	VLD1	(R5), [V12.B16]
	FMOVD	R9, F24
	CMP	$128, R11
	BLT	short

	VLD1.P	64(R13), [V0.B16, V1.B16, V2.B16, V3.B16]
	VLD1.P	64(R13), [V4.B16, V5.B16, V6.B16, V7.B16]
	VEOR	V24.B16, V0.B16, V0.B16
	SUB	$128, R11
	CMP	$128, R11
	BLT	merge8

	// Data is xored into the low product to keep it off the loop-carried path.
loop128:
	VLD1.P	64(R13), [V16.B16, V17.B16, V18.B16, V19.B16]
	VLD1.P	64(R13), [V20.B16, V21.B16, V22.B16, V23.B16]
	VPMULL	V0.D1, V8.D1, V24.Q1
	VPMULL2	V0.D2, V8.D2, V0.Q1
	VPMULL	V1.D1, V8.D1, V25.Q1
	VPMULL2	V1.D2, V8.D2, V1.Q1
	VPMULL	V2.D1, V8.D1, V26.Q1
	VPMULL2	V2.D2, V8.D2, V2.Q1
	VPMULL	V3.D1, V8.D1, V27.Q1
	VPMULL2	V3.D2, V8.D2, V3.Q1
	VPMULL	V4.D1, V8.D1, V28.Q1
	VPMULL2	V4.D2, V8.D2, V4.Q1
	VPMULL	V5.D1, V8.D1, V29.Q1
	VPMULL2	V5.D2, V8.D2, V5.Q1
	VPMULL	V6.D1, V8.D1, V30.Q1
	VPMULL2	V6.D2, V8.D2, V6.Q1
	VPMULL	V7.D1, V8.D1, V31.Q1
	VPMULL2	V7.D2, V8.D2, V7.Q1
	VEOR	V16.B16, V24.B16, V24.B16
	VEOR	V17.B16, V25.B16, V25.B16
	VEOR	V18.B16, V26.B16, V26.B16
	VEOR	V19.B16, V27.B16, V27.B16
	VEOR	V20.B16, V28.B16, V28.B16
	VEOR	V21.B16, V29.B16, V29.B16
	VEOR	V22.B16, V30.B16, V30.B16
	VEOR	V23.B16, V31.B16, V31.B16
	VEOR	V24.B16, V0.B16, V0.B16
	VEOR	V25.B16, V1.B16, V1.B16
	VEOR	V26.B16, V2.B16, V2.B16
	VEOR	V27.B16, V3.B16, V3.B16
	VEOR	V28.B16, V4.B16, V4.B16
	VEOR	V29.B16, V5.B16, V5.B16
	VEOR	V30.B16, V6.B16, V6.B16
	VEOR	V31.B16, V7.B16, V7.B16
	SUB	$128, R11
	CMP	$128, R11
	BGE	loop128

	// Fold V0-V3 into V4-V7 across 64 bytes.
merge8:
	VPMULL	V0.D1, V9.D1, V24.Q1
	VPMULL2	V0.D2, V9.D2, V0.Q1
	VPMULL	V1.D1, V9.D1, V25.Q1
	VPMULL2	V1.D2, V9.D2, V1.Q1
	VPMULL	V2.D1, V9.D1, V26.Q1
	VPMULL2	V2.D2, V9.D2, V2.Q1
	VPMULL	V3.D1, V9.D1, V27.Q1
	VPMULL2	V3.D2, V9.D2, V3.Q1
	VEOR	V24.B16, V4.B16, V4.B16
	VEOR	V25.B16, V5.B16, V5.B16
	VEOR	V26.B16, V6.B16, V6.B16
	VEOR	V27.B16, V7.B16, V7.B16
	VEOR	V0.B16, V4.B16, V4.B16
	VEOR	V1.B16, V5.B16, V5.B16
	VEOR	V2.B16, V6.B16, V6.B16
	VEOR	V3.B16, V7.B16, V7.B16
	CMP	$64, R11
	BLT	merge4

	// One last 64-byte block.
	VLD1.P	64(R13), [V16.B16, V17.B16, V18.B16, V19.B16]
	SUB	$64, R11
	VPMULL	V4.D1, V9.D1, V24.Q1
	VPMULL2	V4.D2, V9.D2, V4.Q1
	VPMULL	V5.D1, V9.D1, V25.Q1
	VPMULL2	V5.D2, V9.D2, V5.Q1
	VPMULL	V6.D1, V9.D1, V26.Q1
	VPMULL2	V6.D2, V9.D2, V6.Q1
	VPMULL	V7.D1, V9.D1, V27.Q1
	VPMULL2	V7.D2, V9.D2, V7.Q1
	VEOR	V16.B16, V24.B16, V24.B16
	VEOR	V17.B16, V25.B16, V25.B16
	VEOR	V18.B16, V26.B16, V26.B16
	VEOR	V19.B16, V27.B16, V27.B16
	VEOR	V24.B16, V4.B16, V4.B16
	VEOR	V25.B16, V5.B16, V5.B16
	VEOR	V26.B16, V6.B16, V6.B16
	VEOR	V27.B16, V7.B16, V7.B16

	// Fold V4-V6 into V7 across 48, 32 and 16 bytes.
merge4:
	VPMULL	V4.D1, V10.D1, V24.Q1
	VPMULL2	V4.D2, V10.D2, V4.Q1
	VPMULL	V5.D1, V11.D1, V25.Q1
	VPMULL2	V5.D2, V11.D2, V5.Q1
	VPMULL	V6.D1, V12.D1, V26.Q1
	VPMULL2	V6.D2, V12.D2, V6.Q1
	VEOR	V24.B16, V4.B16, V4.B16
	VEOR	V25.B16, V5.B16, V5.B16
	VEOR	V26.B16, V6.B16, V6.B16
	VEOR	V4.B16, V7.B16, V7.B16
	VEOR	V5.B16, V6.B16, V6.B16
	VEOR	V6.B16, V7.B16, V7.B16
	CBZ	R11, done

	// Fold the remaining 16-byte blocks into V7.
loop16:
	VLD1.P	16(R13), [V16.B16]
	VPMULL	V7.D1, V12.D1, V24.Q1
	VPMULL2	V7.D2, V12.D2, V7.Q1
	VEOR	V16.B16, V24.B16, V24.B16
	VEOR	V24.B16, V7.B16, V7.B16
	SUBS	$16, R11
	BNE	loop16

done:
	VST1	[V7.B16], (R6)
	RET

	// Fewer than 128 bytes: a single accumulator.
short:
	VLD1.P	16(R13), [V7.B16]
	VEOR	V24.B16, V7.B16, V7.B16
	SUBS	$16, R11
	BNE	loop16
	B	done
